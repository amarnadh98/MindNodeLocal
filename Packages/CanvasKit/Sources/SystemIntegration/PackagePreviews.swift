/// What `PackagePreviews.readPayload(at:)` found in a `.arbor` package:
/// the stored Quick Look payloads and whether each is still fresh
/// relative to `map.json` (SPEC §5.16 F-INT-3, SPEC §8.1).
public struct PackagePreviewPayload: Sendable, Equatable {
    public let thumbnailPNG: Data?
    public let previewPDF: Data?
    public let thumbnailFresh: Bool
    public let previewFresh: Bool

    public init(
        thumbnailPNG: Data?, previewPDF: Data?, thumbnailFresh: Bool, previewFresh: Bool
    ) {
        self.thumbnailPNG = thumbnailPNG
        self.previewPDF = previewPDF
        self.thumbnailFresh = thumbnailFresh
        self.previewFresh = previewFresh
    }
}

/// Reads the `QuickLook/` payloads of a saved `.arbor` package and
/// decides where a thumbnail or preview should come from: the files the
/// app writes on every explicit save (fresh), or a fresh render through
/// `SceneExport`. One choice rule serves the app's save path, the
/// Quick Look extension targets, and the hosted tests (ADR-0027).
public enum PackagePreviews {
    /// The long edge the app's save path writes `Thumbnail.png` at
    /// (SPEC §5.16 F-INT-3).
    public static let storedThumbnailLongEdgePixels = 512

    /// Where a thumbnail comes from for a requested pixel long edge.
    public enum ThumbnailSource: Sendable, Equatable {
        /// Use the stored `QuickLook/Thumbnail.png`, downscaled to the
        /// request. Only chosen when the file is fresh and its 512 px
        /// long edge covers the request.
        case stored
        /// Re-render through the shared scene exporters at this pixel
        /// long edge (fresh file missing/stale, or the request is larger
        /// than the stored raster).
        case render(Int)
    }

    /// The choice rule (pure, testable): a fresh stored thumbnail that
    /// is at least as large as the request wins — it is exactly what the
    /// app's save wrote; anything else re-renders.
    public static func thumbnailSource(
        storedFresh: Bool, requestedLongEdgePixels: Int
    ) -> ThumbnailSource {
        guard storedFresh, requestedLongEdgePixels <= storedThumbnailLongEdgePixels else {
            return .render(max(1, requestedLongEdgePixels))
        }
        return .stored
    }

    /// Reads the package's stored Quick Look payloads and their
    /// freshness. A package that is not a directory, or missing entries,
    /// reads as an all-stale payload — the caller falls back to
    /// rendering, never crashes.
    public static func readPayload(at packageURL: URL) -> PackagePreviewPayload {
        let quickLook = packageURL.appendingPathComponent(ArborPackage.quickLookEntryName)
        let mapEntry = packageURL.appendingPathComponent(ArborPackage.mapEntryName)
        let mapDate = modificationDate(of: mapEntry)
        let thumbnailURL = quickLook.appendingPathComponent("Thumbnail.png")
        let previewURL = quickLook.appendingPathComponent("Preview.pdf")
        return PackagePreviewPayload(
            thumbnailPNG: try? Data(contentsOf: thumbnailURL),
            previewPDF: try? Data(contentsOf: previewURL),
            thumbnailFresh: isFresh(modificationDate(of: thumbnailURL), relativeTo: mapDate),
            previewFresh: isFresh(modificationDate(of: previewURL), relativeTo: mapDate))
    }

    /// Freshness rule: a preview regenerated by the same save that wrote
    /// `map.json` carries a modification date at or after it. Previews
    /// from an earlier save predate the current `map.json` and are
    /// stale. Either file missing reads as stale.
    public static func isFresh(_ previewDate: Date?, relativeTo mapDate: Date?) -> Bool {
        guard let previewDate, let mapDate else { return false }
        return previewDate >= mapDate
    }

    private static func modificationDate(of url: URL) -> Date? {
        try? FileManager.default.attributesOfItem(atPath: url.path)[.modificationDate] as? Date
    }
}

/// Renders the Quick Look payloads through the SAME scene exporters the
/// File ▸ Export… sheet uses (F-INT-3: save == export == extension
/// fallback), and the small image-level helpers the Quick Look extension
/// targets need on top.
public enum ArborPreviewRenderer {
    /// Both payloads the app's save path writes into the package
    /// (512 px PNG thumbnail + whole-map vector PDF). This is the one
    /// implementation behind `MapDocument`'s save, the Quick Look
    /// extensions' fallback, and the tests.
    ///
    /// `theme` is the app's resolved theme for user-themed documents
    /// (F-STY-5). The extensions pass nil and resolve the built-in theme.
    public static func renderPayloads(
        model: MapModel, variant: ThemeVariant, measurer: TextMeasurer = SceneRenderer.sharedMeasurer,
        theme: Theme? = nil
    ) throws -> (thumbnail: Data, preview: Data) {
        let scene = SceneGeometry.build(model: model, variant: variant, measurer: measurer, theme: theme)
        var thumbnailOptions = ImageExportOptions(
            format: .png, targetLongEdgePixels: PackagePreviews.storedThumbnailLongEdgePixels)
        thumbnailOptions.margin = 12
        let thumbnail = try ImageExporter.export(scene: scene, model: model, options: thumbnailOptions)
        let preview = try PDFExporter.export(
            scene: scene,
            model: model,
            options: PDFExportOptions(
                content: .map(.wholeMap), includeBackground: true, includeBookmarks: false,
                title: displayTitle(for: model)))
        return (thumbnail.data, preview)
    }

    /// A thumbnail re-render at an arbitrary pixel long edge (the
    /// Quick Look extension's fallback when the stored PNG is missing,
    /// stale, or smaller than requested).
    public static func renderThumbnail(
        model: MapModel, variant: ThemeVariant, longEdgePixels: Int,
        measurer: TextMeasurer = SceneRenderer.sharedMeasurer
    ) throws -> Data {
        let scene = SceneGeometry.build(model: model, variant: variant, measurer: measurer)
        var options = ImageExportOptions(format: .png, targetLongEdgePixels: longEdgePixels)
        options.margin = 12
        return try ImageExporter.export(scene: scene, model: model, options: options).data
    }

    /// The whole-map preview PDF the preview extension falls back to.
    public static func renderPreviewPDF(
        model: MapModel, variant: ThemeVariant,
        measurer: TextMeasurer = SceneRenderer.sharedMeasurer
    ) throws -> Data {
        let scene = SceneGeometry.build(model: model, variant: variant, measurer: measurer)
        return try PDFExporter.export(
            scene: scene,
            model: model,
            options: PDFExportOptions(
                content: .map(.wholeMap), includeBackground: true, includeBookmarks: false,
                title: displayTitle(for: model)))
    }

    /// The document's title: an explicit `model.title`, else the root's
    /// first line, else "Map" — the same derivation the document's
    /// display name uses (F-EDT-14) so Finder, Spotlight and the window
    /// agree on one name.
    public static func displayTitle(for model: MapModel) -> String {
        if let title = model.title?.trimmingCharacters(in: .whitespacesAndNewlines), !title.isEmpty {
            return title
        }
        guard let rootID = model.roots.first, let root = model.nodes[rootID] else { return "Map" }
        let firstLine = root.title.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? ""
        return firstLine.isEmpty ? "Map" : firstLine
    }

    /// The appearance an extension renders in: the document's explicit
    /// dark override, else light (extensions have no window to follow).
    public static func effectiveVariant(for model: MapModel) -> ThemeVariant {
        model.appearance == .dark ? .dark : .light
    }

    // MARK: image helpers

    /// The stored PNG decoded and downscaled to `maxPixelSize` on its
    /// long edge (never upscaled — a small stored thumbnail is used at
    /// its own size). This is the `.stored` arm of the thumbnail
    /// choice.
    public static func downscaledThumbnailImage(fromPNG png: Data, maxPixelSize: CGFloat) -> CGImage? {
        guard
            let source = CGImageSourceCreateWithData(png as CFData, nil),
            let full = CGImageSourceCreateImageAtIndex(source, 0, nil)
        else { return nil }
        let longEdge = max(full.width, full.height)
        guard CGFloat(longEdge) > maxPixelSize, maxPixelSize > 0 else { return full }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    }

    /// The thumbnail the Quick Look extension returns for a package:
    /// the stored PNG (downscaled) when the choice rule says so, else a
    /// fresh render from the package's `map.json` at the requested size.
    /// `maximumPixelSize` is in points; `scale` converts it to pixels.
    public static func thumbnailImage(
        at packageURL: URL, maximumPixelSize: CGSize, scale: CGFloat
    ) -> CGImage? {
        let payload = PackagePreviews.readPayload(at: packageURL)
        let requestedLongEdge = Int(
            (max(maximumPixelSize.width, maximumPixelSize.height) * scale).rounded(.up))
        switch PackagePreviews.thumbnailSource(
            storedFresh: payload.thumbnailFresh, requestedLongEdgePixels: requestedLongEdge)
        {
        case .stored:
            guard let png = payload.thumbnailPNG else { return nil }
            return downscaledThumbnailImage(
                fromPNG: png, maxPixelSize: CGFloat(requestedLongEdge))
        case .render(let longEdge):
            guard let contents = try? ArborPackage.read(at: packageURL) else { return nil }
            guard
                let data = try? renderThumbnail(
                    model: contents.model, variant: effectiveVariant(for: contents.model),
                    longEdgePixels: longEdge)
            else { return nil }
            return downscaledThumbnailImage(fromPNG: data, maxPixelSize: CGFloat(longEdge))
        }
    }

    /// The preview PDF the Quick Look extension shows: the stored
    /// `Preview.pdf` when fresh, else a fresh render. Nil when the
    /// package can neither be read nor rendered (the extension reports
    /// the error and Quick Look falls back to its own file listing).
    public static func previewPDF(at packageURL: URL) -> Data? {
        let payload = PackagePreviews.readPayload(at: packageURL)
        if let pdf = payload.previewPDF, payload.previewFresh { return pdf }
        guard let contents = try? ArborPackage.read(at: packageURL) else {
            return payload.previewPDF
        }
        return try? renderPreviewPDF(
            model: contents.model, variant: effectiveVariant(for: contents.model))
    }
}
